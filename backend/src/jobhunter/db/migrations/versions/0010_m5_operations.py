"""M5 schema: the deletion manifests, their shipments, the backups and the exports of §7.14, the fence's foreign
key to its manifest, the purged batch items, the dead-man state, the schema-compat record, and the columns
M5 adds to earlier tables.

Revision ID: 0010_m5_operations
Revises: 0009_m4_ui

Staged by docs/superpowers/plans/2026-11-09-m5-operations-privacy-production.md (Task 1), as static SQL, one
`op.execute` per statement:

  §7.14  deletion_manifests, manifest_shipments, manifest_shipment_items, the foreign key
         deletion_manifests.shipment_id -> manifest_shipments, backup_sets, backup_runs and exports, copied
         verbatim from the spec; and purge_fences.manifest_id -> deletion_manifests, the foreign key M0
         Deviation 1 left to M5 (the column was NOT NULL from the start);
  T1     the indexes: deletion_manifests_open (the manifests not shipped yet), manifest_shipment_items_uuid
         (a manifest's shipment by its uuid and file hash), backup_sets_latest (the latest succeeded set),
         backup_runs_latest (the latest run of each kind) and the partial unique exports_one_running (one live
         export, D9);
  T1     purged_batch_items: the content-free evidence that a purge deleted an item of a live submission
         (Task 11, Deviation 13), gone with its submission;
  T1     deadman_state, the single row of the dead-man switch's applied configuration (Task 5; `migrate`'s
         seed inserts it, all NULL), and worker_heartbeat.tracing (Task 6);
  T1     schema_compat: per revision, the oldest revision whose code runs on it and whether its upgrade is
         destructive (`db.compat`; `migrate` records it after Alembic, Task 27 reads it);
  §7.16  one assert_transition trigger per M5 state machine: deletion_manifests, exports, backup_sets and
         backup_runs, each on `status`; `migrate` writes their edges to transition_matrix from the registry.

These are the ONLY differences from the spec text. Each carries a SQL comment naming its plan deviation:

  1. deletion_manifests.request jsonb NOT NULL DEFAULT '{}': the purge's request, ids only, what `compute`
     needs, kept with the manifest so no operation has to carry it (Deviation 53).
  2. exports.size_bytes bigint CHECK (size_bytes >= 0) and exports.purge_generation bigint (Deviation 19).
  3. api_idempotency.id bigint GENERATED ALWAYS AS IDENTITY with UNIQUE (id) (Deviation 24): the table's key
     stays (route, idem_key) and the rows already there are numbered; the surrogate is the one identity
     column that `max_identity_ids` and a `keep` id need. The table is small (its rows live 7 days).
  4. login_lockouts.generation bigint GENERATED BY DEFAULT AS IDENTITY, the rows already there numbered
     (Deviation 16): every lock or renewal takes a new value (`auth.throttle._LOCK_OUT`), since the table has
     no other identity, parent or `created_at` a manifest could bound it by, and its key holds an address.
  5. llm_calls.content_purged_at timestamptz: the marker of a `field_redact llm_calls output_json`, which
     settlement honours (Deviation 54).

No view changes (Ruling T1-a: 0008 keeps reading `views.sql`) and no INSERT.

The compatibility floor is 0009 and the upgrade is not destructive: it only adds tables, columns, indexes,
triggers and a foreign key that the rows of M0-M4 satisfy (no code before M5 writes a purge fence), so M4's
code runs on this schema. The downgrade is exact. It is refused (SQLSTATE 55000) while one of the seven
record tables holds a row (purged_batch_items, exports, backup_runs, backup_sets, manifest_shipment_items,
deletion_manifests, manifest_shipments), a manifest above all: dropping one would lose the record of a purge,
so the database stays at 0010. deadman_state (its seeded row) and schema_compat (`migrate`'s record) hold
derived state and are dropped whatever they hold.
"""

