"""The offline gazetteer (spec §8.12): German places, European cities and country names.

The data are three packaged files under `geo/data/`, read through `importlib.resources`:

- `de_places.tsv` (generated by `scripts/build_gazetteer.py`): German places with their folded name variants,
  coordinates, population and postal codes; the columns are the fields of `Place`, in order;
- `non_de_places.tsv` (generated): the lookup rows of European cities over 100,000 inhabitants and of every
  country name outside Germany; the columns are the fields of `NonDePlace`, in order;
- `country_names_de.tsv` is the hand-maintained German input of the build and is not read here.

Both TSVs start with a header row, use tab as the separator and join list-valued cells with `|`. All lookup
keys are `fold`ed (spec §8.1), so callers pass `fold(text)`; `search` folds its query itself because it
serves user input.
"""

import bisect
import functools
import math
from collections import defaultdict
from collections.abc import Iterable
from dataclasses import dataclass, fields
from importlib.resources import files
from typing import Final, Literal

from jobhunter.normalize.text import fold

_EARTH_RADIUS_KM: Final = 6371.0088
# A degree of latitude is at least this long, so `km / _MIN_KM_PER_DEGREE` degrees never miss a point.
_MIN_KM_PER_DEGREE: Final = 110.5
_LIST_SEPARATOR: Final = "|"


def distance_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """The great-circle distance between two WGS84 points in kilometres (haversine)."""
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    d_phi = phi2 - phi1
    d_lambda = math.radians(lon2 - lon1)
    a = math.sin(d_phi / 2) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(d_lambda / 2) ** 2
    return 2 * _EARTH_RADIUS_KM * math.asin(min(1.0, math.sqrt(a)))


@dataclass(frozen=True)
class Place:
    """A German place. `folded` is the folded `name`; `alt_folded` its other folded spellings."""

    gazetteer_id: str  # f"geonames:{geonameid}"
    name: str
    folded: str
    alt_folded: tuple[str, ...]
    country_code: str
    admin1: str  # the GeoNames admin1 code of the federal state, e.g. "05" for Hessen
    lat: float
    lon: float
    population: int
    postal_codes: tuple[str, ...]


@dataclass(frozen=True)
class NonDePlace:
    """One lookup row of a place outside Germany: a city (or one of its names) or a country name.

    `folded` is the lookup key; for a city it is the folded `name` or one of the city's other names, so one
    city has several rows. `gazetteer_id`, `lat` and `lon` identify and place a city, so that a parsed
    location can carry it as a candidate; a country has none of the three.
    """

    name: str
    folded: str
    country_code: str
    kind: Literal["city", "country"]
    gazetteer_id: str = ""
    lat: float | None = None
    lon: float | None = None


PLACE_COLUMNS: Final = tuple(f.name for f in fields(Place))
NON_DE_COLUMNS: Final = tuple(f.name for f in fields(NonDePlace))


def _table(text: str, columns: tuple[str, ...], what: str) -> list[list[str]]:
    """The rows of a TSV text without its header row; every row has exactly `len(columns)` cells."""
    lines = text.split("\n")
    if lines[0] != "\t".join(columns):
        raise ValueError(f"{what}: unexpected header {lines[0]!r}")
    rows = [line.split("\t") for line in lines[1:] if line]
    for number, row in enumerate(rows, start=2):
        if len(row) != len(columns):
            raise ValueError(f"{what} line {number}: {len(row)} cells, expected {len(columns)}")
    return rows


def _split(cell: str) -> tuple[str, ...]:
    return tuple(cell.split(_LIST_SEPARATOR)) if cell else ()


def _place(row: list[str]) -> Place:
    return Place(
        gazetteer_id=row[0],
        name=row[1],
        folded=row[2],
        alt_folded=_split(row[3]),
        country_code=row[4],
        admin1=row[5],
        lat=float(row[6]),
        lon=float(row[7]),
        population=int(row[8]),
        postal_codes=_split(row[9]),
    )


def _non_de_place(row: list[str]) -> NonDePlace:
    kind: Literal["city", "country"]
    if row[3] == "city":
        kind = "city"
    elif row[3] == "country":
        kind = "country"
    else:
        raise ValueError(f"non_de_places: unknown kind {row[3]!r}")
    return NonDePlace(
        name=row[0],
        folded=row[1],
        country_code=row[2],
        kind=kind,
        gazetteer_id=row[4],
        lat=float(row[5]) if row[5] else None,
        lon=float(row[6]) if row[6] else None,
    )


class Gazetteer:
    """Lookups over the packaged places. Instances are immutable; use `Gazetteer.load()`."""

    def __init__(self, places: Iterable[Place], non_de: Iterable[NonDePlace]) -> None:
        # Most populous first, so every result list below is in that order.
        self._places: Final = tuple(sorted(places, key=lambda p: (-p.population, p.name, p.gazetteer_id)))
        by_name: defaultdict[str, list[Place]] = defaultdict(list)
        by_postal: defaultdict[str, list[Place]] = defaultdict(list)
        # (key, rank, place index) for `search`: rank 0 for the name and the postal codes, 1 for a spelling
        prefixes: list[tuple[str, int, int]] = []
        for index, place in enumerate(self._places):
            for name in (place.folded, *place.alt_folded):
                by_name[name].append(place)
            for code in place.postal_codes:
                by_postal[code].append(place)
            prefixes.append((place.folded, 0, index))
            prefixes.extend((code, 0, index) for code in place.postal_codes)
            prefixes.extend((alt, 1, index) for alt in place.alt_folded)
        prefixes.sort()
        self._by_name: Final = dict(by_name)
        self._by_postal: Final = dict(by_postal)
        self._prefix_keys: Final = [key for key, _, _ in prefixes]
        self._prefix_hits: Final = [(rank, index) for _, rank, index in prefixes]

        non_de_by_key: dict[str, NonDePlace] = {}
        cities: dict[str, NonDePlace] = {}
        for row in non_de:
            if row.folded in non_de_by_key:
                raise ValueError(f"non_de_places: duplicate key {row.folded!r}")
            non_de_by_key[row.folded] = row
            if row.kind == "city":
                cities.setdefault(row.gazetteer_id, row)
        self._non_de: Final = non_de_by_key

        located: list[tuple[float, float, Place | NonDePlace]] = [(p.lat, p.lon, p) for p in self._places]
        located.extend((c.lat, c.lon, c) for c in cities.values() if c.lat is not None and c.lon is not None)
        located.sort(key=lambda t: t[0])
        self._located: Final = located
        self._located_lats: Final = [t[0] for t in located]

    @classmethod
    def load(cls) -> "Gazetteer":
        """The gazetteer of the packaged data files; read once per process."""
        return _packaged()

    @classmethod
    def from_tsv(cls, de_places: str, non_de_places: str) -> "Gazetteer":
        """A gazetteer over TSV texts in the packaged format (the packaged files, or a test's own)."""
        places = [_place(row) for row in _table(de_places, PLACE_COLUMNS, "de_places")]
        non_de = [_non_de_place(row) for row in _table(non_de_places, NON_DE_COLUMNS, "non_de_places")]
        return cls(places, non_de)

    def by_name(self, folded: str) -> list[Place]:
        """The places whose `folded` or any `alt_folded` equals `folded`, most populous first."""
        return list(self._by_name.get(folded, ()))

    def by_postal_code(self, code: str) -> list[Place]:
        """The places a postal code maps to, most populous first."""
        return list(self._by_postal.get(code, ()))

    def search(self, q: str, limit: int = 10) -> list[Place]:
        """Places whose folded name, postal code or other spelling starts with `fold(q)`.

        Places that match by name or postal code come first, those that match only by another spelling
        (`Munich` for München) after them; each group is ordered by population. The empty query matches every
        place. This backs the scope-location autocomplete (spec §14.2).
        """
        if limit <= 0:
            return []
        prefix = fold(q)
        keys = self._prefix_keys
        best: dict[int, int] = {}  # place index -> best rank
        for i in range(bisect.bisect_left(keys, prefix), len(keys)):
            if not keys[i].startswith(prefix):
                break
            rank, index = self._prefix_hits[i]
            best[index] = min(rank, best.get(index, rank))
        ordered = sorted(best, key=lambda index: (best[index], index))  # indexes follow the population order
        return [self._places[index] for index in ordered[:limit]]

    def non_de(self, folded: str) -> NonDePlace | None:
        """The non-German city or country that `folded` names, if any."""
        return self._non_de.get(folded)

    def is_german_place_name(self, folded: str) -> bool:
        return folded in self._by_name

    def nearest(self, lat: float, lon: float, max_km: float = 50.0) -> Place | NonDePlace | None:
        """The closest German place or non-German city within `max_km` of the point, if there is one."""
        window = max_km / _MIN_KM_PER_DEGREE
        lats = self._located_lats
        best: Place | NonDePlace | None = None
        best_km = max_km
        for i in range(bisect.bisect_left(lats, lat - window), bisect.bisect_right(lats, lat + window)):
            place_lat, place_lon, place = self._located[i]
            km = distance_km(lat, lon, place_lat, place_lon)
            if km <= best_km:
                best, best_km = place, km
        return best


@functools.cache
def _packaged() -> Gazetteer:
    data = files("jobhunter.geo").joinpath("data")
    return Gazetteer.from_tsv(
        data.joinpath("de_places.tsv").read_text(encoding="utf-8"),
        data.joinpath("non_de_places.tsv").read_text(encoding="utf-8"),
    )
